export function campaignStyle(presetId, textMode, useScene = false, overlayText = false) {
  const preset = getStylePreset(presetId);
  const system = SYSTEMS[presetId];
  if (!preset || !system) throw new Error('套图风格无效');
  const [background, secondary, text, accent, lighting] = system;
  return {
    palette: [background, secondary, text, accent],
    text: [
      `整套视觉规范：${preset.name}。背景主色 ${background}，辅助底色 ${secondary}，文字色 ${text}，强调色 ${accent}；实际商品的原色保持不变。`,
      useScene
        ? `全套光线：${lighting}。已引用场景参考时，带场景的页面必须以场景参考构建真实环境与背景，不得改成纯色色板铺底或纯白棚拍；仅白底商品首图固定纯白，以及明确不使用场景的细节页可不出现场景。风格色板只约束文案、留白与非场景页面的衬色。`
        : `全套光线：${lighting}。仅 H1 白底商品首图固定纯白背景，其余页面按各自主题采用所选色板、细节分区或真实使用环境，不能全套复制白底居中商品照。`,
      '全套版式：统一 8% 外边距和对齐规律，但按本页主题改变主次、景别与分区；商品整体、局部定位窗与场景图交替组织，不能每页都套同一种居中单商品构图。商品各视图必须保持真实形状和比例。',
      textMode === 'facts'
        ? '文字与图标：统一简洁无衬线字体，标题、说明、注释字号比例 2:1:0.8；只使用本页列出的真实文案。必要的信息图使用统一 2px 等效线宽和强调色，不绘制无依据的功能或认证图标。'
        : overlayText
          ? '文字由系统后期排版；底图仍须完成本页的商业设计、色块分区、细节小窗或场景层次。只禁止生成额外文字、数字、认证与功能图标，不禁止有依据的商品细节排版。保留商品原有包装字样。'
          : '不添加额外文字、数字、营销标签或功能图标，保留商品原有包装字样；仍按本页要求完成构图、细节分区与场景。',
      useScene
        ? '全套保持相同的光线方向、留白、字体与图标样式；带场景页面的环境以场景参考为准。每页独立成图，页面之间不混入不同商品或不同模特。'
        : '全套保持相同的色板、光线方向、留白、字体与图标样式。每页独立成图，页面之间不混入不同商品或不同模特。',
    ].join('\n'),
  };
}
